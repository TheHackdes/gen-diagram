const HYPERVISOR_SIZE = { width: 420, height: 280 };
const GUESTS = ['vm', 'lxc', 'docker-host', 'bridge', 'storage'];

const hypervisorFields = (versionPlaceholder: string): FieldDef[] => [
  F.hostname,
  F.ip,
  { key: 'version', label: 'Version', type: 'text', placeholder: versionPlaceholder },
  F.vlan,
  { key: 'cluster', label: 'Cluster', type: 'text', placeholder: 'pve-cluster-01' },
  F.network,
  F.gateway,
  F.description,
  F.cpu,
  F.ram,
  F.disk,
  F.mac,
  F.vendor,
  F.model,
  F.serial,
  F.location,
];

function hypervisor(type: string, label: string, icon: string, color: string, description: string, version: string, extra: Partial<ComponentDefinition> = {}) {
  return container({
    type,
    label,
    category: 'virtualization',
    role: 'hypervisor',
    icon,
    color,
    description,
    fields: hypervisorFields(version),
    size: HYPERVISOR_SIZE,
    accepts: GUESTS,
    quickAdd: ['vm', 'lxc', 'docker-host', 'bridge', 'storage'],
    portPattern: ethPorts('eno', 1),
    ...extra,
  });
}

