/** Self-contained HTML document (diagram embedded); print it to get a PDF. */
export function toHtml(doc: DocModel, image?: string): string {
  const sections = doc.sections
    .map((s) => {
      const parts = [`<section id="${anchor(s.id)}"><h2>${esc(s.title)}</h2>`];
      if (s.intro) parts.push(`<p class="intro">${esc(s.intro)}</p>`);
      if (s.facts) parts.push(`<dl>${s.facts.map((f) => `<div><dt>${esc(f.label)}</dt><dd>${esc(f.value)}</dd></div>`).join('')}</dl>`);
      if (s.image) parts.push(image ? `<figure><img src="${image}" alt="Diagram of ${esc(doc.title)}"></figure>` : '<p class="empty">The diagram is empty.</p>');
      for (const t of s.tables) parts.push(htmlTable(t));
      if (!s.facts && !s.image && !s.tables.length && s.empty) parts.push(`<p class="empty">${esc(s.empty)}</p>`);
      parts.push('</section>');
      return parts.join('');
    })
    .join('\n');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(doc.title)} — infrastructure documentation</title>
<style>${STYLE}</style>
</head>
<body>
<main>
<header><h1>${esc(doc.title)}</h1>${doc.description ? `<p>${esc(doc.description)}</p>` : ''}<p>Infrastructure documentation · ${esc(dateOf(doc.generatedAt))}</p></header>
<nav aria-label="Contents">${doc.sections.map((s) => `<a href="#${anchor(s.id)}">${esc(s.title)}</a>`).join('')}</nav>
${sections}
<footer>Generated by InfraCanvas from the project diagram.</footer>
</main>
</body>
</html>
`;
}
