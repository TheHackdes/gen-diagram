import type { DocModel, DocTable } from './document';

const dateOf = (iso: string) => new Date(iso).toLocaleString(undefined, { dateStyle: 'long', timeStyle: 'short' });

// --- Markdown ------------------------------------------------------------------

const mdCell = (v: string) => (v || ' ').replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>');

function mdTable(t: DocTable): string {
  const out: string[] = [];
  if (t.title) out.push(`### ${t.title}`, '');
  if (t.note) out.push(`_${t.note}_`, '');
  out.push(`| ${t.columns.map(mdCell).join(' | ')} |`, `| ${t.columns.map(() => '---').join(' | ')} |`);
  for (const r of t.rows) out.push(`| ${r.map(mdCell).join(' | ')} |`);
  out.push('');
  return out.join('\n');
}

/** Markdown document. `image` is the file name (or data URL) of the diagram picture. */
export function toMarkdown(doc: DocModel, image?: string): string {
  const out: string[] = [`# ${doc.title}`, ''];
  if (doc.description) out.push(doc.description, '');
  out.push(`_Generated by InfraCanvas on ${dateOf(doc.generatedAt)}._`, '');
  for (const s of doc.sections) {
    out.push(`## ${s.title}`, '');
    if (s.intro) out.push(s.intro, '');
    if (s.facts) {
      for (const f of s.facts) out.push(`- **${f.label}:** ${f.value}`);
      out.push('');
    }
    if (s.image) out.push(image ? `![Diagram of ${doc.title}](${image})` : '_The diagram is empty._', '');
    for (const t of s.tables) out.push(mdTable(t));
    if (!s.facts && !s.image && !s.tables.length && s.empty) out.push(`_${s.empty}_`, '');
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n');
}

// --- HTML ----------------------------------------------------------------------

const esc = (v: string) => v.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const anchor = (id: string) => `s-${id}`;

const SEVERITY = new Set(['error', 'warning', 'info']);
const ACTIONS = new Set(['allow', 'deny', 'allow (disabled)', 'deny (disabled)']);

function htmlCell(v: string, col: string): string {
  if (col === 'Severity' && SEVERITY.has(v)) return `<td><span class="tag ${v}">${esc(v)}</span></td>`;
  if (col === 'Action' && ACTIONS.has(v)) return `<td><span class="tag ${v.split(' ')[0]}">${esc(v)}</span></td>`;
  const mono = ['Address', 'Addresses', 'Subnet', 'Gateway', 'Port', 'Ports', 'VLANs', 'ID', '#'].includes(col);
  return `<td${mono ? ' class="mono"' : ''}>${esc(v)}</td>`;
}

function htmlTable(t: DocTable): string {
  return [
    t.title ? `<h3>${esc(t.title)}</h3>` : '',
    t.note ? `<p class="note">${esc(t.note)}</p>` : '',
    '<div class="table"><table><thead><tr>',
    ...t.columns.map((c) => `<th>${esc(c)}</th>`),
    '</tr></thead><tbody>',
    ...t.rows.map((r) => `<tr>${r.map((v, i) => htmlCell(v, t.columns[i])).join('')}</tr>`),
    '</tbody></table></div>',
  ].join('');
}

